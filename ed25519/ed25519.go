// hashParts is plumbing around the existing, self-written SHA-512 package.
// It computes SHA-512 over concatenated parts without modifying their backing
// arrays. Only tests may use crypto/sha512 or crypto/ed25519 as an oracle.
func hashParts(parts ...[]byte) [64]byte {
	h := labsha512.New()
	for _, part := range parts {
		_, _ = h.Write(part)
	}
	var out [64]byte
	copy(out[:], h.Sum(nil))
	return out
}

